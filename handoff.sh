    background:radial-gradient(60% 50% at 10% 0%,#ffd6e8 0%,transparent 70%),
               radial-gradient(50% 50% at 100% 20%,#e3d9ff 0%,transparent 70%),
               radial-gradient(60% 60% at 50% 100%,#d4f7ec 0%,transparent 70%),#fff8fb;
    padding:48px 20px 60px}
  .wrap{max-width:980px;margin:0 auto}
  header{text-align:center;margin-bottom:28px}
  .hi{font-family:Fredoka,sans-serif;font-weight:600;color:var(--pink);letter-spacing:.08em;text-transform:uppercase;font-size:14px}
  h1{font-family:Fredoka,sans-serif;font-weight:700;font-size:clamp(36px,7vw,60px);margin:6px 0 8px;line-height:1.05;
     background:linear-gradient(90deg,var(--pink),var(--lav) 55%,#5fc8a8);-webkit-background-clip:text;background-clip:text;color:transparent}
  .sub{color:var(--muted);font-weight:600;margin:0}
  .search{display:block;margin:26px auto 30px;width:min(420px,100%);padding:14px 20px;border-radius:999px;border:2px solid #f1e4f7;
