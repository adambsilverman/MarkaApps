  const q=document.getElementById('q'),cards=[...document.querySelectorAll('.card')],empty=document.getElementById('empty');
  q.addEventListener('input',()=>{const t=q.value.trim().toLowerCase();let n=0;
    cards.forEach(c=>{const ok=!t||c.dataset.search.includes(t);c.style.display=ok?'':'none';n+=ok});
    empty.style.display=n?'none':'block';});
