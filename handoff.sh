#!/usr/bin/env bash
# handoff.sh — rebuild index.html from every app in this folder, then commit & push to GitHub.
#
# Usage:   ./handoff.sh                 # auto commit message
#          ./handoff.sh "added bio quiz" # custom commit message
#          ./handoff.sh --no-push        # just rebuild index.html
#
# Each app is any *.html file in this folder (except index.html).
# Optional tags inside an app's <head> control its card on the index:
#   <meta name="marka-icon" content="🧬">
#   <meta name="description" content="Cell parts practice for Friday's test">
#   <meta name="marka-subject" content="Biology">
# Without them, the card uses the page <title> and a guessed icon/subject.

set -euo pipefail
cd "$(dirname "$0")"

NO_PUSH=0; MSG=""
for a in "$@"; do
  if [ "$a" = "--no-push" ]; then NO_PUSH=1; else MSG="$a"; fi
done

esc() { sed -e 's/&/\&amp;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g' -e 's/"/\&quot;/g'; }
urlenc() { printf '%s' "$1" | sed -e 's/%/%25/g' -e 's/ /%20/g' -e 's/#/%23/g' -e 's/?/%3F/g' -e "s/'/%27/g"; }
meta() { # meta <file> <name>
  tr '\n' ' ' < "$1" | grep -o "<meta[^>]*name=[\"']$2[\"'][^>]*>" | head -1 \
    | sed -n "s/.*content=[\"']\([^\"']*\)[\"'].*/\1/p" || true
}
guess() { # guess <lowercased text> -> "icon|subject"
  case "$1" in
    *spanish*|*español*|*espanol*) echo "🌶️|Spanish";;
    *french*|*français*)           echo "🥐|French";;
    *odyssey*|*iliad*|*homer*|*greek*|*myth*) echo "🏛️|English";;
    *english*|*novel*|*poem*|*essay*|*shakespeare*|*vocab*) echo "📖|English";;
    *algebra*|*geometry*|*math*|*equation*) echo "📐|Math";;
    *bio*|*cell*|*dna*|*genetic*)  echo "🧬|Biology";;
    *chem*|*atom*|*periodic*)      echo "⚗️|Chemistry";;
    *physics*|*earth*|*science*)   echo "🔭|Science";;
    *history*|*war*|*civics*|*government*) echo "📜|History";;
    *) echo "✨|Study";;
  esac
}

CARDS=""; N=0
while IFS= read -r -d '' f; do
  f="${f#./}"
  [ "$f" = "index.html" ] && continue
  title=$(tr '\n' ' ' < "$f" | sed -n 's:.*<title>\([^<]*\)</title>.*:\1:p' | sed 's/^ *//;s/ *$//')
  [ -z "$title" ] && title="${f%.html}"
  g=$(guess "$(printf '%s %s' "$title" "$f" | tr '[:upper:]' '[:lower:]')")
  icon=$(meta "$f" marka-icon); [ -z "$icon" ] && icon="${g%%|*}"
  subj=$(meta "$f" marka-subject); [ -z "$subj" ] && subj="${g##*|}"
  desc=$(meta "$f" description)
  descp=""; [ -n "$desc" ] && descp="<p>$(printf '%s' "$desc" | esc)</p>"
  updated=$(git log -1 --format=%cs -- "$f" 2>/dev/null || true)
  [ -z "$updated" ] && updated=$(date +%F)
  CARDS+="      <a class=\"card\" href=\"$(urlenc "$f")\" data-search=\"$(printf '%s %s %s' "$title" "$subj" "$desc" | tr '[:upper:]' '[:lower:]' | esc)\">
        <span class=\"icon\">$icon</span>
        <span class=\"tag\">$(printf '%s' "$subj" | esc)</span>
        <h2>$(printf '%s' "$title" | esc)</h2>
        $descp
        <span class=\"date\">updated $updated</span>
      </a>
"
  N=$((N+1))
done < <(find . -maxdepth 1 -name '*.html' -print0 | sort -z)

BUILT=$(date '+%b %-d, %Y'); PLURAL=s; [ "$N" = 1 ] && PLURAL=
cat > index.html <<HTML
