  <div class="wrap">
    <header>
      <div class="hi">hey Marka 💖</div>
      <h1>Study Hub</h1>
      <p class="sub">$N study app$PLURAL · pick one and get it done ✌️</p>
    </header>
    <input class="search" id="q" type="search" placeholder="🔍  find an app…" autocomplete="off">
    <main class="grid" id="grid">
$CARDS    </main>
    <p class="empty" id="empty">nothing matches that 🤔</p>
    <footer>last updated $BUILT</footer>
  </div>
