</body>
</html>
HTML
echo "✓ index.html rebuilt with $N app(s)"

[ "$NO_PUSH" = 1 ] && exit 0

git add -A
if git diff --cached --quiet; then
  echo "✓ nothing new to commit"
else
  [ -z "$MSG" ] && MSG="Update apps: $(git diff --cached --name-only | grep -v '^index.html$' | sed 's/\.html$//' | paste -sd ',' - | sed 's/,/, /g')"
  [ "$MSG" = "Update apps: " ] && MSG="Update index"
  git commit -m "$MSG"
fi
git push origin HEAD
echo "✓ pushed to GitHub"
